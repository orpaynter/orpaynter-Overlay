import { chromium } from '/mnt/c/Users/OrPay/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ executablePath: '/root/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome', headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const checks = [], errors = [];
let captures = 0;
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (request.url().includes('/api/orpaynter/observations') && !request.url().includes('snapshotId=')) captures++; });
const check = (name, result) => { assert.ok(result, name); checks.push(name); };
const base = 'http://127.0.0.1:4180';
try {
  await page.goto(base + '/?layers=satellites,earthquakes', { waitUntil: 'domcontentloaded', timeout: 120000 });
  await page.getByRole('heading', { name: 'ORPAYNTER OVERLAY', exact: true }).waitFor({ timeout: 60000 });
  await page.waitForTimeout(15000);
  check('Overlay product identity and real globe visible', await page.locator('canvas.maplibregl-canvas').count() === 1 && (await page.title()).startsWith('OrPaynter Overlay'));
  check('upstream credit is accessible from operating surface', await page.getByRole('link', { name: /credits & licenses/ }).count() === 1);
  await page.getByRole('button', { name: 'Open OrPaynter workspace' }).click();
  const pane = page.getByRole('region', { name: 'OrPaynter intelligence workspace' });
  const freeze = pane.getByRole('button', { name: 'Freeze this capture' });
  await freeze.waitFor();
  await page.waitForFunction(() => !document.querySelector('.orpa-time-modes button:nth-child(2)')?.disabled, undefined, { timeout: 45000 });
  await freeze.click();
  check('freeze stops manual capture replacement', await pane.getByRole('button', { name: 'Refresh source snapshot' }).isDisabled());
  const job = await (await page.request.get(base + '/api/orpaynter/grok')).json();
  check('existing completed owner job retained', job.runId === '0091dc92-6deb-4f81-869a-79c4050c8c56' && job.status === 'completed');
  const loaded = page.waitForResponse(r => r.url().includes('snapshotId=' + job.snapshotId));
  await pane.getByRole('button', { name: 'Open saved job capture' }).click();
  const response = await loaded, snapshot = await response.json();
  check('saved job retrieves original exact capture', response.ok() && snapshot.id === job.snapshotId && snapshot.capturedAt && snapshot.feeds.some(f => f.rawHash));
  await pane.getByText('ID ' + snapshot.id.slice(0, 10), { exact: false }).waitFor();
  const before = captures;
  await page.waitForTimeout(62000);
  check('frozen capture survives periodic refresh window unchanged', captures === before && (await pane.locator('.orpa-capture-meta').innerText()).includes(snapshot.id.slice(0, 10)));
  check('frozen mode scope clearly labeled', (await pane.locator('[data-capture-mode]').innerText()).includes('globe and company reads continue updating separately'));
  await page.screenshot({ path: 'orpaynter-evidence/overlay-capture.png' });
  const resumed = page.waitForResponse(r => r.url().endsWith('/api/orpaynter/observations') && r.ok(), { timeout: 45000 });
  await pane.getByRole('button', { name: 'Updating sources' }).click();
  await resumed;
  check('updating mode resumes source capture', await pane.getByRole('button', { name: 'Updating sources' }).getAttribute('aria-pressed') === 'true');
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open OrPaynter workspace' }).click();
  check('capture controls remain inside mobile viewport', await pane.locator('.orpa-time-modes').evaluate(e => e.getBoundingClientRect().right <= window.innerWidth));
  await page.screenshot({ path: 'orpaynter-evidence/overlay-mobile.png' });
  await page.goto(base + '/credits', { waitUntil: 'domcontentloaded' });
  check('visible contributor and catalogue credit retained', (await page.locator('body').innerText()).includes('simplifaisoul') && (await page.locator('body').innerText()).includes('Bram and Annelies'));
  check('credits distinguish software from connected data and services', (await page.locator('body').innerText()).includes('does not make every connected service or dataset open source'));
  check('no uncaught browser errors', errors.length === 0);
  await fs.writeFile('orpaynter-evidence/overlay-browser-qa.json', JSON.stringify({ checkedAt: new Date().toISOString(), passed: checks.length, checks, errors, snapshotId: job.snapshotId }, null, 2));
  console.log(JSON.stringify({ passed: checks.length }));
} finally { await browser.close(); }
